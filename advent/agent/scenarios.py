"""
Сценарии — заготовленные диалоги для сравнения агентов в одинаковых условиях.

Задания дней 8–10 просят сравнивать «на одном и том же диалоге». Один
сценарий, прогнанный с разными лимитами и стратегиями, даёт честное
сравнение — и на видео это одна кнопка вместо десяти минут печати.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Scenario:
    key: str
    title: str
    description: str
    messages: tuple[str, ...]


# «Собираем ТЗ» — из примера в задании дня 10. Каждая реплика добавляет
# факт, последняя просит собрать всё вместе: по ней видно, что агент
# потерял, когда контекст режется или сжимается.
SPEC_GATHERING = Scenario(
    key="spec",
    title="Собираем ТЗ",
    description="Двенадцать реплик: каждая добавляет требование, последняя просит собрать всё в одно ТЗ.",
    messages=(
        "Помоги собрать ТЗ на мобильное приложение для учёта личных расходов. "
        "Отвечай коротко, одним-двумя предложениями, просто подтверждай и уточняй.",
        "Платформа — только Android, минимальная версия 10.",
        "Основная валюта — рубли, но нужна поддержка долларов и евро.",
        "Категории расходов пользователь создаёт сам, предустановленных не нужно.",
        "Обязательно офлайн-режим: без интернета всё должно работать.",
        "Синхронизация между устройствами — через аккаунт Google.",
        "Бюджет на разработку — 800 тысяч рублей, срок — три месяца.",
        "Дизайн: тёмная тема по умолчанию, светлая — опционально.",
        "Экспорт данных в CSV, импорт не нужен.",
        "Уведомления: раз в день напоминание внести расходы, время настраивается.",
        "Никакой рекламы и подписок — приложение платное, 299 рублей.",
        "Теперь собери всё, что я сказал, в короткое ТЗ списком. Ничего не упусти: "
        "платформа, валюты, категории, офлайн, синхронизация, бюджет и срок, дизайн, "
        "экспорт, уведомления, цена.",
    ),
)

SCENARIOS: dict[str, Scenario] = {SPEC_GATHERING.key: SPEC_GATHERING}


def get_scenario(key: str) -> Scenario | None:
    return SCENARIOS.get(key)
